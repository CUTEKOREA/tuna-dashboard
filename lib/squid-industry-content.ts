/**
 * 「시장 이해 > 오징어」 서술 콘텐츠 — 밸류체인 7단계 + 횡단 3축
 *
 * 참치 페이지(`tuna-industry-content.ts`)와 같은 골격이다. 이 페이지의 본체는 차트가
 * 아니라 **설명**이고, 차트는 설명의 근거로 붙는다.
 *
 * 수치 출처는 셋이다.
 *   · FAO FishStat 2026.1.0 어획통계 (1950~2024) — `scripts/build_squid_industry_data.py`
 *   · 관세청 수출입무역통계 HSK 10자리 (2020~2024, 2026년 1~6월) — `scripts/build_squid_trade_data.py`
 *   · 기존 오징어 위젯 39개의 1차 출처 아카이브 — `scripts/curate_squid_industry_widgets.py`
 *
 * 신뢰도 등급
 *   A — 기관 1차문서·공식 통계 원문 확인 (FAO·관세청·남태평양 공해 관리기구·해양수산부)
 *   B — 기관 2차 인용
 *   C — 업계 매체
 *
 * ⚠ 이 품목의 최대 함정은 **바스켓**이다. 오징어·갑오징어·문어를 자동 합산하지 않는다.
 *   어획 통계와 통관 통계는 범위도 중량 기준도 달라(생중량 대 제품중량) 두 수치를
 *   직접 빼거나 나누면 안 된다. 본문에서 두 수치를 나란히 놓을 때는 그 사실을 함께 적는다.
 *
 * 표기 규약: 본문의 `「」` 는 **그 단계에 실린 위젯·차트 제목을 가리킬 때만** 쓴다.
 * 강조 인용은 `“”` 를 쓴다. 테스트가 이 규약을 강제한다.
 */

export type SourceGrade = 'A' | 'B' | 'C';

/** 본문에서 인용하는 검증된 수치 한 줄. */
export interface SquidFactRow {
  label: string;
  /** 표시할 값. 단위를 포함해 문자열로 고정한다(포맷 흔들림 방지) */
  value: string;
  asOf: string;
  source: string;
  grade: SourceGrade;
  note?: string;
}

export interface SquidTermDef {
  term: string;
  description: string;
}

export interface SquidStageNarrative {
  /** 큐레이션 JSON 의 stage.key 와 일치해야 한다 */
  key: string;
  /** 사슬 단계는 '01'~'07', 횡단축은 'A'~'C' */
  numeral: string;
  title: string;
  question: string;
  lede: string;
  paragraphs: string[];
  facts: SquidFactRow[];
  terms: SquidTermDef[];
}

