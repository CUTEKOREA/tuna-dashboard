/** 숫자 칸만 골라 쓴다 — IMO·증서번호·날짜는 문자열이다. */
function n(key: string): number {
  const v = data.stats[key];
  if (typeof v !== 'number') throw new Error(`capsen stats.${key} 가 숫자가 아니다`);
  return v;
}

