/**
 * 영업보고의 월별 수주와 주간 원장의 신규수주(주차 말일이 속한 달로 묶음)를 나란히 놓는다.
 * 기준이 다르다 - 주간 원장은 월 경계를 걸친 주의 수주를 그 주 말일의 달에 넣는다. 차이는 그 몫이다.
 */
export function ordersVsLedger() {
  const ledger = new Map<number, { fcl: number; usd: number }>();
  for (const w of weeks) {
    const month = Number(String(w.periodEnd).split('/')[0]);
    const cur = ledger.get(month) ?? { fcl: 0, usd: 0 };
    cur.fcl += Number(w.new_orders_fcl ?? 0);
    cur.usd += Number(w.new_orders_usd ?? 0);
    ledger.set(month, cur);
  }
  return cosmoSalesReport.ordersYtd.map((m) => ({
    month: m.month,
    reportFcl: m.fcl,
    reportUsd: m.usd,
    ledgerFcl: ledger.get(m.month)?.fcl ?? 0,
    ledgerUsd: ledger.get(m.month)?.usd ?? 0,
  }));
}
