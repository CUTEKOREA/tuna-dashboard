export type SourceGrade = 'A' | 'B' | 'C';

/** 본문에서 인용하는 검증된 수치 한 줄. */
export interface FactRow {
  /** 무엇을 재는 값인가 — 한글 라벨 */
  label: string;
  /** 표시할 값. 단위를 포함해 문자열로 고정한다(포맷 흔들림 방지) */
  value: string;
  /** 기준 시점 — 연도 또는 기간 */
  asOf: string;
  /** 출처 기관 */
  source: string;
  grade: SourceGrade;
  /** 이 숫자가 왜 중요한가 — 한 줄. 없으면 표시하지 않는다 */
  note?: string;
}

/** 전문 용어 해설 (TermTooltip 으로 노출). */
export interface TermDef {
  term: string;
  description: string;
}

export interface StageNarrative {
  /** 큐레이션 JSON 의 stage.key 와 일치해야 한다 */
  key: string;
  /** 사슬 단계는 '01'~'07', 횡단축은 'A'~'C' */
  numeral: string;
  title: string;
  /** 이 단계가 답하는 질문 */
  question: string;
  /** 한 문장 요약 */
  lede: string;
  /** 본문. 각 원소가 한 문단이다 */
  paragraphs: string[];
  facts: FactRow[];
  terms: TermDef[];
}

