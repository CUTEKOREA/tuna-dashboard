const data = raw as unknown as {
  _meta: { 회사: string; 국가: string; 업종: string; 종목: string; 출처: string; 조사일: string };
  card: { numeral: string; tagline: string };
  stats: Record<string, number | string>;
  sourcenotes: string[];
};

/** 숫자 칸만 골라 쓴다 — `법인명`·`EU인가번호`·`주소`는 문자열이다. */
function n(key: string): number {
  const v = data.stats[key];
  if (typeof v !== 'number') throw new Error(`sca stats.${key} 가 숫자가 아니다`);
  return v;
}

export const scaMeta = data._meta;
export const scaCard = data.card;
export const scaStats = data.stats;
export const scaSourceNotes = data.sourcenotes;

